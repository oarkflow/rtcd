const { chromium } = require(process.env.PLAYWRIGHT || 'playwright');
const fs = require('fs'), crypto = require('crypto');
const BASE = process.env.BASE || 'http://127.0.0.1:8481', SHOTS = process.env.SHOTS || require('os').tmpdir();
// Drives two Chrome windows through the demo; see ../README.md.
const ok = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ✓', m); };
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required'] });
  const mk = async (name) => {
    const ctx = await browser.newContext({ viewport: { width: 1360, height: 860 }, acceptDownloads: true, permissions: ['camera', 'microphone'] });
    const page = await ctx.newPage(); const errs = [];
    page.on('pageerror', e => errs.push('pageerror: ' + e.message));
    page.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
    page.on('response', async r => { if (r.status() >= 400 && !/\/v1\/(ice|files)/.test(r.url())) errs.push('HTTP ' + r.status() + ' ' + r.url() + ' ' + (await r.text().catch(() => '')).slice(0, 200) + ' @' + new Date().toISOString().slice(17, 23)); });
    await page.goto(BASE);
    await page.fill('#name', name); await page.click('text=Continue');
    await page.waitForSelector('.app');
    return { page, errs, name };
  };
  try {
    const ada = await mk('ada'), bob = await mk('bob');
    await ada.page.screenshot({ path: SHOTS + '/01-empty.png' });
    console.log('chat');
    await ada.page.click('.list-title button');
    await ada.page.fill('.modal input >> nth=0', 'Project Atlas'); await ada.page.fill('.modal input >> nth=1', 'bob');
    await ada.page.click('.modal button.primary');
    await ada.page.waitForSelector('.chip.ok:has-text("End-to-end encrypted")');
    ok(true, 'ada created the group and holds the key');
    await bob.page.click('.conv >> text=Project Atlas');
    await bob.page.waitForSelector('.chip.ok:has-text("End-to-end encrypted")', { timeout: 15000 });
    ok(true, 'bob received the wrapped key and is encrypted');
    await ada.page.fill('textarea', 'Hello Bob — this is encrypted 🔐'); await ada.page.keyboard.press('Enter');
    await bob.page.waitForSelector('.bubble:has-text("Hello Bob")', { timeout: 8000 });
    ok(true, 'bob read ada\'s message');
    ok(await ada.page.locator('.msg.me .bubble:has-text("Hello Bob")').count() === 1, 'ada also sees her own message text');
    await bob.page.fill('textarea', 'Got it, Ada. <b>not bold</b> <img src=x onerror=alert(1)>'); await bob.page.keyboard.press('Enter');
    await ada.page.waitForSelector('.bubble:has-text("Got it, Ada")');
    ok(await ada.page.locator('.bubble b').count() === 0 && await ada.page.locator('.bubble img').count() === 0, 'HTML in a message is shown as text, not run');
    console.log('attachment');
    const data = crypto.randomBytes(2.3 * 1024 * 1024 | 0); const f = require('path').join(require('os').tmpdir(), '_rtcd_up.bin'); fs.writeFileSync(f, data);
    await ada.page.setInputFiles('input[type=file]', f);
    await bob.page.waitForSelector('.file b:has-text("_rtcd_up.bin")', { timeout: 20000 });
    const [dl] = await Promise.all([bob.page.waitForEvent('download'), bob.page.click('.file .btn:has-text("Save")')]);
    const got = fs.readFileSync(await dl.path());
    ok(Buffer.compare(got, data) === 0, 'bob downloaded and decrypted the 2.3 MB file, byte for byte');
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64'); fs.writeFileSync(require('path').join(require('os').tmpdir(), '_rtcd_pic.png'), png);
    await ada.page.setInputFiles('input[type=file]', require('path').join(require('os').tmpdir(), '_rtcd_pic.png'));
    await bob.page.waitForSelector('img.preview', { timeout: 15000 });
    ok(true, 'an image is previewed after decrypting it in the browser');
    await bob.page.waitForTimeout(500);
    await ada.page.screenshot({ path: SHOTS + '/02-chat-ada.png' }); await bob.page.screenshot({ path: SHOTS + '/03-chat-bob.png' });
    await ada.page.click('[aria-label="Group info"] , button[aria-label="Group info"]');
    await ada.page.waitForSelector('.info.open .mono');
    const code1 = await ada.page.textContent('.info.open .mono');
    await bob.page.click('button[aria-label="Group info"]'); await bob.page.waitForSelector('.info.open .mono');
    const code2 = await bob.page.textContent('.info.open .mono');
    ok(code1 === code2 && /^(\d{5} ){11}\d{5}$/.test(code1), 'both members show the same safety code: ' + code1);
    await ada.page.screenshot({ path: SHOTS + '/04-info.png' });
    console.log('diagnostics');
    await ada.page.click('button:has-text("Diagnostics")');
    await ada.page.click('button:has-text("Run all checks")');
    await ada.page.waitForSelector('button:has-text("Run again")', { timeout: 90000 });
    const res = await ada.page.evaluate(() => [...document.querySelectorAll('.check')].map(c => [c.className.replace('check ', ''), c.querySelector('b').textContent, c.querySelector('.detail')?.textContent]));
    for (const [s, n, d] of res) console.log('   ', s === 'pass' ? '✓' : s.toUpperCase(), n, s === 'pass' ? '' : '— ' + d);
    await ada.page.screenshot({ path: SHOTS + '/05-diagnostics.png', fullPage: false });
    ok(res.every(r => r[0] === 'pass'), 'all ' + res.length + ' diagnostic checks pass in the browser');
    console.log('call');
    await ada.page.click('button:has-text("Chats")'); await ada.page.click('.conv >> text=Project Atlas');
    await ada.page.click('button:has-text("Call")');
    await bob.page.waitForSelector('.toast:has-text("is calling")', { timeout: 10000 });
    await bob.page.click('.toast button:has-text("Join")');
    for (const p of [ada, bob]) await p.page.waitForSelector('.tile:not(.local) video.live', { timeout: 30000 });
    ok(true, 'both sides are showing the other\'s decrypted video');
    await ada.page.waitForTimeout(3500);
    const stats = await Promise.all([ada, bob].map(p => p.page.evaluate(() => { const v = document.querySelector('.tile:not(.local) video'); return { w: v.videoWidth, h: v.videoHeight, stats: document.querySelector('.controls .chip').textContent, code: document.querySelector('.call-top .chip.ok:nth-of-type(2), .call-top [title^=Compare]').textContent }; })));
    console.log('   ', JSON.stringify(stats));
    console.log('    pc stats:', JSON.stringify(await ada.page.evaluate(async () => { const r = await __rtcd.call.pc.getStats(); const o = []; r.forEach(x => { if (/rtp/.test(x.type)) o.push([x.type, x.kind, x.bytesReceived ?? x.bytesSent, x.framesDecoded ?? x.framesEncoded]); if (x.type === 'candidate-pair' && x.state === 'succeeded') o.push(['pair', x.nominated, x.currentRoundTripTime]); }); return o; })));
    ok(stats.every(s => s.w > 0 && /received/.test(s.stats) && !/ 0 received/.test(s.stats)), 'remote video has a picture and encrypted frames were decrypted');
    await ada.page.screenshot({ path: SHOTS + '/06-call.png' });
    await ada.page.click('button[aria-label="Leave the call"]'); await bob.page.click('button[aria-label="Leave the call"]');
    await ada.page.waitForSelector('.call', { state: 'hidden' });
    ok(true, 'both left cleanly');
    for (const p of [ada, bob]) if (p.errs.length) console.log('  console errors for', p.name, p.errs);
    ok(![ada, bob].some(p => p.errs.some(e => !/Failed to load resource|^HTTP 4(01|29)|HTTP Authentication failed/.test(e))), 'no JavaScript errors on either page (expected 401/429 from the checks aside)');
    console.log('\nALL UI CHECKS PASSED');
  } catch (e) { console.error('\nFAILED:', e.message); process.exitCode = 1; }
  finally { await browser.close(); }
})();
